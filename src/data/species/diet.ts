/** 合并食性字段，并在年代说明末尾追加食性依据。 */
export function withDiet(s: Species): Species {
  const d = DIET[s.id];
  if (!d) return s;
  return { ...s, diet: d[0], evidenceNote: `${s.evidenceNote} 食性：${d[1]}` };
}
