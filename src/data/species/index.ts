import { calBpToYearsAgo, maToYearsAgo, type HabitatId, type Species, type TimeRange } from "../schema";

/**
 * PLAN §5.3 的代表性生物。
 *
 * 年代范围的取得方式（每条记录的 evidenceNote 中注明）：
 *   [文献]  取自已核对 DOI 的文献给出的首末出现年代；
 *   [地层]  以化石所在地层单元（ICS v2024/12）的边界表示，精度受限于地层分辨率；
 *   [PBDB] 没有可用文献时，取 PBDB 化石记录年代中值的 2.5%–97.5% 分位
 *          （剔除少量误归类记录造成的离群值），仅作展示用近似。
 * 分布一律为 PBDB 化石点（现代坐标，非当时古地理位置，风险 R5），
 * 由 scripts/fetch-pbdb-sites.mjs 按上述年代范围过滤后生成。
 * "若干现代动植物"尚未收录（缺少逐条核实的来源）。
 */

const ma = (fromMa: number, toMa: number, unc?: [number, number]): TimeRange => ({
  fromYearsAgo: maToYearsAgo(fromMa),
  toYearsAgo: maToYearsAgo(toMa),
  ...(unc ? { uncertaintyYears: { older: maToYearsAgo(unc[0]), younger: maToYearsAgo(unc[1]) } } : {}),
});

